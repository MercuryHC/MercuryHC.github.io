const assert = require('node:assert/strict'), fs = require('node:fs'), vm = require('node:vm');
const R = require('./reminders-core'), M = require('./merge-core'), S = require('./storage-core'), P = require('./project-store'), N = require('./notification-core');
const now = '2026-11-25T12:00:00.000Z', later = '2026-11-25T13:00:00.000Z';
const item = R.create('  事项  ', later, 'reminder-a', now);
assert.equal(item.title, '事项'); assert.deepEqual(R.normalize(undefined), []);
assert.deepEqual(R.normalize(JSON.parse(JSON.stringify([item]))), [item]);
for (const bad of [null, false, {}, [item,item], [{...item,remindAt:'bad'}], [{...item,remindAt:'2026-02-30T10:00:00Z'}], [{...item,remindAt:'2026-11-25T24:00:00Z'}], [{...item,completed:'false'}], [{...item,title:' '}], [{...item,completed:true}], [{...item,updatedAt:'bad'}]]) assert.throws(() => R.normalize(bad));
const done = R.complete(item, true, later), restored = R.complete(done, false, later);
assert.equal(done.completedAt, later); assert.equal(restored.completedAt, null);
assert.equal(R.overdue(item, Date.parse(later)+1), true); assert.equal(R.overdue(done, Date.parse(later)+1), false);
assert.equal(R.overdue(item, Date.parse(now)), false);
const edited = R.edit(item, '修改', now, later); assert.equal(edited.createdAt, now);
assert.equal(R.select([done, {...item,id:'b'}], 'pending').length, 1);
assert.equal(R.select([done, {...item,id:'b'}], 'completed').length, 1);
assert.equal(R.select([done, {...item,id:'b'}], 'all')[0].id, 'b');
assert.equal(R.toLocal(R.fromLocal('2026-11-26T09:30')), '2026-11-26T09:30');
assert.throws(() => R.fromLocal('2026-02-30T09:30'));
const data = reminders => ({projects:[],tasks:[],schedules:[],reminders});
const base = data([item]);
let plan = M.plan(data([]),base,base); assert.equal(M.build(plan).data.reminders.length,0,'one-sided deletion');
plan = M.plan(data([done]),data([edited]),base); assert.equal(M.build(plan).unresolved.length,1);
plan.rows[0].choice='remote'; assert.equal(M.build(plan).data.reminders[0].title,'修改');
assert.equal(M.build(M.plan(data([item]),{projects:[],tasks:[]},null)).data.reminders.length,1);
plan = M.plan(data([]),data([edited]),base); assert.equal(M.build(plan).unresolved.length,1,'delete/edit conflict');
const wrap = x => ({tasks:x});
plan = S.plan(wrap(data([])),wrap(base),wrap(base),['tasks']); assert.equal(S.build(plan).tasks.reminders.length,0);
plan = S.plan(wrap(data([done])),wrap(data([edited])),wrap(base),['tasks']); assert.equal(plan.rows.filter(r=>r.conflict).length,1);
plan.rows.find(r=>r.conflict).choice='local'; assert.equal(S.build(plan).tasks.reminders[0].completed,true);
const partitions=P.split({projects:[{id:'p'}],tasks:[{id:'t',project:'p'}],schedules:[],reminders:[item]});
assert.deepEqual(partitions.get('@reminders').reminders,[item]); assert.equal(partitions.get('p').reminders.length,0);
assert.notEqual(P.stable(base),P.stable(data([done])));
assert.equal(P.stable({projects:[],tasks:[]}),P.stable(data([])));
const git = fs.readFileSync(__dirname+'/github-sync.js','utf8');
const validate = vm.runInNewContext('('+git.slice(git.indexOf('function validateData(data)'),git.indexOf('  function encodeData'))+')', {window:{ReminderCore:R}});
assert.equal(validate({projects:[],tasks:[]}).reminders.length,0);
assert.equal(JSON.stringify(validate(base).reminders),JSON.stringify([item]));
assert.throws(()=>validate(data([{...item,title:''}])));
global.TaskTime=require('./task-time');
assert.deepEqual(N.validate(N.snapshot(base)).reminders,[item]);
assert.equal(N.validate({tasks:[]}).reminders.length,0);
assert.equal(N.pendingAll({tasks:[],reminders:[item]}, {}, Date.parse(now)).length,0);
let pending=N.pendingAll({tasks:[],reminders:[item]}, {}, Date.parse(later)); assert.equal(pending.length,1);
const sent={[pending[0].key]:3};
assert.equal(N.pendingAll({tasks:[],reminders:[item]},sent,Date.parse(later)+1).length,0);
assert.equal(N.pendingAll({tasks:[],reminders:[done]}, {}, Date.parse(later)+1).length,0);
assert.equal(N.pendingAll({tasks:[],reminders:[restored]}, {}, Date.parse(later)+1).length,1);
assert.equal(N.pendingAll({tasks:[],reminders:[edited]},sent,Date.parse(later)+1).length,1,'rescheduling creates a new notification key');
assert.notEqual(N.reminderSignature(item),N.signature({id:item.id,priority:'高',dueAt:Date.parse(later)}));
console.log('PASS: reminder validation, CRUD states, filters/time zones, legacy data, roundtrip, both merge engines, delete/edit conflicts, partitioning and due/completed/rescheduled notification dedupe.');
